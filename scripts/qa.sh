#!/usr/bin/env bash
# ==============================================================================
# FinZvit Automated QA & Verification Script
# Проганяє всі тести Python та білд веб-додатка перед коммітом
# ==============================================================================

set -e

RED='\033[0;31m'
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

echo -e "${BLUE}================================================================${NC}"
echo -e "${BLUE}🛡️  FinZvit QA Suite: Перевірка перед комітом/деплоєм${NC}"
echo -e "${BLUE}================================================================${NC}"

# 1. Сканування безпеки на витік секретів
echo -e "\n${YELLOW}[1/3] 🔒 Сканування на витік секретів, токенів та приватних ключів...${NC}"
if python3 scripts/security_check.py; then
    echo -e "${GREEN}✓ Секретів або небезпечних файлів конфігурації не виявлено!${NC}"
else
    echo -e "${RED}✗ Знайдено потенційний витік секретів! Виправте проблему перед створенням коміту.${NC}"
    exit 1
fi

# 2. Тести Python (ETL, Парсери, Фін. калькулятор, Розрахунки 2350/2355)
echo -e "\n${YELLOW}[2/3] 🧪 Запуск автоматичних тестів Python (67 тестів)...${NC}"
if python3 -m unittest discover -v tests; then
    echo -e "${GREEN}✓ Всі Python-тести успішно пройдено!${NC}"
else
    echo -e "${RED}✗ Помилка у тестах Python. Виправте помилки перед створенням коміту!${NC}"
    exit 1
fi

# 3. Білд фронтенду (Astro + React + Vite + TypeScript)
echo -e "\n${YELLOW}[3/3] 🔨 Перевірка збірки фронтенду (web build)...${NC}"
if npm run build --prefix web; then
    echo -e "${GREEN}✓ Збірка фронтенду успішна! TypeScript та шаблони без помилок.${NC}"
else
    echo -e "${RED}✗ Помилка збірки веб-додатка. Перевірте типи або синтаксис!${NC}"
    exit 1
fi

echo -e "\n${GREEN}================================================================${NC}"
echo -e "${GREEN}✅ ВСІ ПЕРЕВІРКИ ПРОЙДЕНО УСПІШНО! Проєкт готовий до коміту.${NC}"
echo -e "${GREEN}================================================================${NC}"
